// Reuses cached runtime. In-process local EVM only, no downloads or disk ledger.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '../..');
const runtime = createRequire(path.join(root, 'Providers/Blockchain/NextGenSoftware.OASIS.API.Providers.Web3CoreOASIS/package.json'));
process.env.HARDHAT_CONFIG = path.join(root, 'Providers/Blockchain/NextGenSoftware.OASIS.API.Providers.Web3CoreOASIS/hardhat.config.cjs');
process.env.HARDHAT_NETWORK = 'hardhat';
const hardhat = runtime('hardhat');
const solc = runtime('solc');
const { ethers } = runtime('ethers');

(async () => {
  const source = fs.readFileSync(path.join(root, 'Providers/Shared/Contracts/OASISKeyValueStore.sol'), 'utf8');
  const output = JSON.parse(solc.compile(JSON.stringify({ language: 'Solidity', sources: { 'store.sol': { content: source } },
    settings: { evmVersion: 'paris', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } } })));
  const errors = (output.errors || []).filter(x => x.severity === 'error');
  assert.equal(errors.length, 0, errors.map(x => x.formattedMessage).join('\n'));
  const compiled = output.contracts['store.sol'].OASISKeyValueStore;
  const provider = new ethers.BrowserProvider(hardhat.network.provider);
  provider.pollingInterval = 50;
  const owner = await provider.getSigner(0);
  const outsider = await provider.getSigner(1);
  const store = await new ethers.ContractFactory(compiled.abi, compiled.evm.bytecode.object, owner).deploy();
  await store.waitForDeployment();
  assert.equal(await store.owner(), await owner.getAddress());
  assert.deepEqual(Array.from(await store.get('missing')), [false, '']);
  await assert.rejects(store.connect(outsider).put('a', 'bad'));
  await assert.rejects(store.connect(outsider).remove('a'));
  await assert.rejects(store.put('', 'bad'));
  await (await store.put('a', '')).wait();
  assert.deepEqual(Array.from(await store.get('a')), [true, '']);
  await (await store.put('b', 'second')).wait();
  await (await store.put('c', 'third')).wait();
  const revision = await store.revision();
  const first = await store.keyPage(revision, 0, 2);
  assert.deepEqual(Array.from(first[0]), ['a', 'b']);
  assert.equal(first[1], 2n);
  assert.equal(first[2], 3n);
  const last = await store.keyPage(revision, first[1], 2);
  assert.deepEqual(Array.from(last[0]), ['c']);
  assert.equal(last[1], 3n);
  await (await store.put('b', 'updated é')).wait();
  assert.deepEqual(Array.from(await store.get('b')), [true, 'updated é']);
  await assert.rejects(store.keyPage(revision, 2, 2));
  const beforeMissingDelete = await store.revision();
  await (await store.remove('missing')).wait();
  assert.equal(await store.revision(), beforeMissingDelete);
  await (await store.remove('a')).wait();
  assert.deepEqual(Array.from(await store.get('a')), [false, '']);
  const page = await store.keyPage(await store.revision(), 0, 256);
  assert.deepEqual(Array.from(page[0]).sort(), ['b', 'c']);
  assert.equal(page[2], 2n);
  await (await store.remove('c')).wait();
  await (await store.remove('b')).wait();
  assert.equal((await store.keyPage(await store.revision(), 0, 256))[2], 0n);
  await (await store.put('a', 'reinserted')).wait();
  assert.deepEqual(Array.from(await store.get('a')), [true, 'reinserted']);
  await assert.rejects(store.keyPage(await store.revision(), 0, 0));
  await assert.rejects(store.keyPage(await store.revision(), 0, 257));
  await assert.rejects(store.keyPage(await store.revision(), 2, 1));
  console.log('Shared key-value local EVM ownership/CRUD/pagination checks PASS');
})().then(() => process.exit(0), error => { console.error(error); process.exit(1); });
