#!/usr/bin/env python3
"""Generate one Postman collection per WEB6-WEB10 API from its REST controllers (--check: exit 1 if stale)."""
import sys
import generate_web4_full_postman as g

stale = []
for n in range(6, 11):
    g.CONTROLLERS = g.ROOT / f"WEB{n}/NextGenSoftware.OASIS.Web{n}.WebAPI/Controllers"
    if not g.CONTROLLERS.is_dir():
        print(f"WEB{n}: controllers not checked out, skipped")
        continue
    g.TARGET = g.ROOT / f"Docs/Devs/API Documentation/WEB{n}/WEB{n}-Full-API.postman_collection.json"
    collection, total = g.build()
    base = "{{web%dBaseUrl}}" % n
    collection["info"] = {"name": f"WEB{n} OASIS API (all routes)", "schema": collection["info"]["schema"],
                          "description": f"{total} requests generated by Scripts/generate_web6_10_postman.py. "
                                         f"Set web{n}BaseUrl and bearerToken."}
    collection["variable"] = [{"key": f"web{n}BaseUrl", "value": ""}, {"key": "bearerToken", "value": ""}]
    for folder in collection["item"]:
        for item in folder["item"]:
            item["request"]["url"] = item["request"]["url"].replace("{{web4BaseUrl}}", base)
    text = g.json.dumps(collection, indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not g.TARGET.exists() or g.TARGET.read_text(encoding="utf-8") != text:
            stale.append(f"WEB{n}")
    else:
        g.TARGET.parent.mkdir(parents=True, exist_ok=True)
        g.TARGET.write_text(text, encoding="utf-8", newline="\n")
        print(f"WEB{n}: {total} requests")
if stale:
    sys.exit("stale Postman collections: " + ", ".join(stale))
