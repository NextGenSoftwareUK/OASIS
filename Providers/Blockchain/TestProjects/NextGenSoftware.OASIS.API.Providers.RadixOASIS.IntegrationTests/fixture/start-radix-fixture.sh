# Starts the disposable local Radix Babylon network for RadixNativeStorageConformanceTests. Source it from bash with the
# repository root as the working directory and $fixture set to an existing "$RUNNER_TEMP/oasis-native.*" directory:
#   source "Providers/Blockchain/TestProjects/NextGenSoftware.OASIS.API.Providers.RadixOASIS.IntegrationTests/fixture/start-radix-fixture.sh"
#
# It builds the OASIS Scrypto package (contracts/) with the official reproducible scrypto-builder, generates a fresh
# single-validator localnet genesis (network 240, with a faucet) with the node's own GenesisBuilder, and starts one
# babylon-node whose ledger lives in $fixture/radix-db, so a container restart keeps it. It appends the node container
# id to $container for the caller's cleanup and exports OASIS_RADIX_CORE_API, OASIS_RADIX_ENGINE_STATE_API and
# OASIS_RADIX_PACKAGE_DIR. No public network, faucet or funds are involved.
radix_node_image="docker.io/radixdlt/babylon-node@sha256:46a50a6c508906d63df2b142d794a3fb0e38269e9e130d5d4ca5b67f827d16f4"   # v1.4.0.0
radix_builder_image="docker.io/radixdlt/scrypto-builder@sha256:b3d580781de5fb636e0cfe63fbc05b91db2c886fe8307839ccf04a43481a0b50" # v1.3.1
radix_fixture_dir="Providers/Blockchain/TestProjects/NextGenSoftware.OASIS.API.Providers.RadixOASIS.IntegrationTests/fixture"
radix_contracts="Providers/Blockchain/NextGenSoftware.OASIS.API.Providers.RadixOASIS/contracts"

[[ -n "${fixture:-}" && -d "$fixture" && "$fixture" == "$RUNNER_TEMP"/oasis-native.* ]] || { echo "\$fixture must be an existing \$RUNNER_TEMP/oasis-native.* directory"; return 1; }
[[ -f "$radix_contracts/Cargo.toml" ]] || { echo "Run from the repository root"; return 1; }
radix_wait() { for attempt in $(seq 1 "${2:-90}"); do if eval "$1" >/dev/null 2>&1; then return 0; fi; sleep 2; done; echo "Never became ready: $1"; return 1; }

# 1. The package: build a copy so the checkout gets no target/ directory or root-owned files.
mkdir -p "$fixture/radix-src" "$fixture/radix-package" "$fixture/radix-keys" "$fixture/radix-db" "$fixture/radix-genesis-class"
cp -r "$radix_contracts/Cargo.toml" "$radix_contracts/Cargo.lock" "$radix_contracts/src" "$fixture/radix-src/" || return 1
# RADIX_BUILDER_DOCKER_ARGS lets a local run pass its egress proxy settings to the crates.io download.
docker run --rm ${RADIX_BUILDER_DOCKER_ARGS:-} -v "$fixture/radix-src:/src" "$radix_builder_image" > "$fixture/radix-build.log" 2>&1 || { tail -n 40 "$fixture/radix-build.log"; return 1; }
cp "$fixture/radix-src/target/wasm32-unknown-unknown/release/oasis_storage.wasm" \
   "$fixture/radix-src/target/wasm32-unknown-unknown/release/oasis_storage.rpd" "$fixture/radix-package/" || return 1

# 2. Genesis and validator key, generated by the node's own libraries.
radix_keystore_password="$(openssl rand -hex 16)"
radix_lib="$fixture/radix-lib"
radix_lib_container="$(docker create "$radix_node_image")" || return 1
docker cp "$radix_lib_container:/opt/radixdlt/lib" "$radix_lib" >/dev/null; radix_copy=$?
docker rm "$radix_lib_container" >/dev/null
(( radix_copy == 0 )) || return 1
javac -proc:none --release 17 -cp "$radix_lib/*" -d "$fixture/radix-genesis-class" "$radix_fixture_dir/GenerateLocalnetGenesis.java" || return 1
chmod 777 "$fixture/radix-keys"
docker run --rm --entrypoint java -v "$fixture/radix-genesis-class:/gen:ro" -v "$fixture/radix-keys:/out" "$radix_node_image" \
  --enable-preview -Djava.library.path=/usr/lib/jni -cp "/gen:/opt/radixdlt/lib/*" GenerateLocalnetGenesis /out "$radix_keystore_password" || return 1

# 3. The node. A lone validator proposes rounds back to back and every round is a ledger version, so the CPU cap bounds
# ledger growth; old state-tree versions and the account change index, which nothing reads, are off; transaction status needs the
# local execution index, so it stays on.
radix_node="$(docker run -d --cpus 0.5 -p 127.0.0.1:13333:3333 -p 127.0.0.1:13336:3336 \
  -v "$fixture/radix-keys:/home/radixdlt/keys" -v "$fixture/radix-db:/home/radixdlt/RADIXDB" \
  -e RADIXDLT_NETWORK_ID=240 -e RADIXDLT_GENESIS_DATA="$(cat "$fixture/radix-keys/genesis.b64")" \
  -e RADIXDLT_VALIDATOR_KEY_LOCATION=/home/radixdlt/keys/node.ks -e RADIX_NODE_KEYSTORE_PASSWORD="$radix_keystore_password" \
  -e RADIXDLT_NETWORK_SEEDS_REMOTE= -e RADIXDLT_HOST_IP_ADDRESS=127.0.0.1 \
  -e RADIXDLT_DB_ACCOUNT_CHANGE_INDEX_ENABLE=false \
  -e RADIXDLT_STATE_HASH_TREE_STATE_VERSION_HISTORY_LENGTH=1000 -e RADIXDLT_STATE_HASH_TREE_GC_INTERVAL_SEC=10 \
  -e JAVA_OPTS="--enable-preview -Xms512m -Xmx1g" "$radix_node_image")" || return 1
container="${container:+$container }$radix_node"
radix_wait "curl -fsS -X POST -H 'Content-Type: application/json' -d '{\"network\":\"localnet\"}' http://127.0.0.1:13333/core/lts/transaction/construction" || return 1
export OASIS_RADIX_CORE_API="http://127.0.0.1:13333/core/" OASIS_RADIX_ENGINE_STATE_API="http://127.0.0.1:13336/engine-state/" \
  OASIS_RADIX_PACKAGE_DIR="$fixture/radix-package"
