        public override async Task<OASISResult<IEnumerable<IHolon>>> LoadAllHolonsAsync(HolonType type = HolonType.All, bool loadChildren = true, bool recursive = true, int maxChildDepth = 0, int curentChildDepth = 0, bool continueOnError = true, bool loadChildrenFromProvider = false, int version = 0)
        {
            var result = new OASISResult<IEnumerable<IHolon>>();
            try
            {
                var response = await _http.GetAsync($"/collections/{_holonCollection}/records");
                if (response.IsSuccessStatusCode)
                {
                    var body = await response.Content.ReadFromJsonAsync<JsonElement>();
                    var holons = new List<IHolon>();
                    var records = body.TryGetProperty("data", out var d) ? d : (body.ValueKind == JsonValueKind.Array ? body : default);
                    if (records.ValueKind == JsonValueKind.Array)
                        foreach (var rec in records.EnumerateArray()) holons.Add(RecordToHolon(rec));
                    result.Result = holons;
                }
                else OASISErrorHandling.HandleError(ref result, $"PolybaseOASIS: LoadAllHolons failed ({response.StatusCode}).");
            }
            catch (Exception ex) { result.Exception = ex; OASISErrorHandling.HandleError(ref result, ex.Message); }
            return result;
        }
