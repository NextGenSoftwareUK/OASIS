        public override async Task<OASISResult<IHolon>> LoadHolonAsync(string providerKey, bool loadChildren = true, bool recursive = true, int maxChildDepth = 0, bool continueOnError = true, bool loadChildrenFromProvider = false, int version = 0)
        {
            var result = new OASISResult<IHolon>();
            try
            {
                var response = await _http.GetAsync($"/collections/{_holonCollection}/records/{Uri.EscapeDataString(providerKey)}");
                if (response.IsSuccessStatusCode)
                {
                    var body = await response.Content.ReadFromJsonAsync<JsonElement>();
                    result.Result = RecordToHolon(body);
                }
                else OASISErrorHandling.HandleError(ref result, $"PolybaseOASIS: LoadHolon '{providerKey}' failed ({response.StatusCode}).");
            }
            catch (Exception ex) { result.Exception = ex; OASISErrorHandling.HandleError(ref result, ex.Message); }
            return result;
        }
