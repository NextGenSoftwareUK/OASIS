        public override async Task<OASISResult<IEnumerable<IHolon>>> LoadHolonsForParentAsync(Guid id, HolonType type = HolonType.All, bool loadChildren = true, bool recursive = true, int maxChildDepth = 0, int curentChildDepth = 0, bool continueOnError = true, bool loadChildrenFromProvider = false, int version = 0)
        {
            // Fetch all and filter in-memory by parentId (Polybase lacks native join)
            var result = new OASISResult<IEnumerable<IHolon>>();
            var allResult = await LoadAllHolonsAsync(type, loadChildren, recursive, maxChildDepth, curentChildDepth, continueOnError, loadChildrenFromProvider, version);
            if (allResult.IsError) { OASISErrorHandling.HandleError(ref result, allResult.Message); return result; }
            result.Result = (allResult.Result ?? Enumerable.Empty<IHolon>()).Where(h => h.ParentHolonId == id).ToList();
            return result;
        }
        public override OASISResult<IEnumerable<IHolon>> LoadHolonsForParent(Guid id, HolonType type = HolonType.All, bool loadChildren = true, bool recursive = true, int maxChildDepth = 0, int curentChildDepth = 0, bool continueOnError = true, bool loadChildrenFromProvider = false, int version = 0)
