        public override async Task<OASISResult<ISearchResults>> SearchAsync(ISearchParams searchParams, bool loadChildren = true, bool recursive = true, int maxChildDepth = 0, bool continueOnError = true, int version = 0)
        {
            var result = new OASISResult<ISearchResults>();
            try
            {
                var query = searchParams.SearchGroups?.OfType<SearchTextGroup>().FirstOrDefault()?.SearchQuery ?? "";
                // Search by treating query as an address and returning recent transactions
                var txResult = await LoadHolonsForParentAsync(query);
                var sr = new SearchResults();
                sr.SearchResultHolons = (txResult.Result ?? Enumerable.Empty<IHolon>())
                    .Where(h => h.Name != null && h.Name.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                                h.ProviderUniqueStorageKey.TryGetValue(Core.Enums.ProviderType.ZkSyncSSOOASIS, out var k) && (k?.Contains(query, StringComparison.OrdinalIgnoreCase) ?? false))
                    .ToList();
                result.Result = sr;
            }
            catch (Exception ex) { result.Exception = ex; OASISErrorHandling.HandleError(ref result, ex.Message); }
            return result;
        }
