        private static IHolon TxToHolon(JsonElement tx)
        {
            var holon = new Holon();
            if (tx.TryGetProperty("hash", out var h)) { holon.ProviderUniqueStorageKey[Core.Enums.ProviderType.ZkSyncSSOOASIS] = h.GetString() ?? ""; holon.Name = h.GetString(); }
            if (tx.TryGetProperty("from", out var f)) holon.MetaData["zksync_from"] = f.GetString() ?? "";
            if (tx.TryGetProperty("to", out var t) && t.ValueKind != JsonValueKind.Null) holon.MetaData["zksync_to"] = t.GetString() ?? "";
            if (tx.TryGetProperty("value", out var v)) holon.MetaData["zksync_value"] = v.GetString() ?? "";
            if (tx.TryGetProperty("blockNumber", out var bn)) holon.MetaData["zksync_block"] = bn.GetString() ?? "";
            return holon;
        }

        public override async Task<OASISResult<IHolon>> LoadHolonAsync(string providerKey, bool loadChildren = true, bool recursive = true, int maxChildDepth = 0, bool continueOnError = true, bool loadChildrenFromProvider = false, int version = 0)
        {
            var result = new OASISResult<IHolon>();
            try
            {
                var tx = await RpcAsync("eth_getTransactionByHash", new object[] { providerKey });
                result.Result = TxToHolon(tx);
            }
            catch (Exception ex) { result.Exception = ex; OASISErrorHandling.HandleError(ref result, ex.Message); }
            return result;
        }
