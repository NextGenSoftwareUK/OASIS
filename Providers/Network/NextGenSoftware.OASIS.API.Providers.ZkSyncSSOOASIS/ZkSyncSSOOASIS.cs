        public override async Task<OASISResult<IEnumerable<IHolon>>> LoadHolonsForParentAsync(string providerKey, HolonType type = HolonType.All, bool loadChildren = true, bool recursive = true, int maxChildDepth = 0, int curentChildDepth = 0, bool continueOnError = true, bool loadChildrenFromProvider = false, int version = 0)
        {
            // Uses ZKsync Era block explorer API for tx list
            var result = new OASISResult<IEnumerable<IHolon>>();
            try
            {
                var response = await _explorerHttp.GetAsync($"/api?module=account&action=txlist&address={providerKey}&sort=desc");
                if (response.IsSuccessStatusCode)
                {
                    var body = await response.Content.ReadFromJsonAsync<JsonElement>();
                    var holons = new List<IHolon>();
                    if (body.TryGetProperty("result", out var results) && results.ValueKind == JsonValueKind.Array)
                        foreach (var tx in results.EnumerateArray()) holons.Add(TxToHolon(tx));
                    result.Result = holons;
                }
                else OASISErrorHandling.HandleError(ref result, $"ZkSyncSSOOASIS: Tx list for '{providerKey}' failed ({response.StatusCode}).");
            }
            catch (Exception ex) { result.Exception = ex; OASISErrorHandling.HandleError(ref result, ex.Message); }
            return result;
        }
