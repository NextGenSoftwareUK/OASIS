        public override async Task<OASISResult<IAvatar>> LoadAvatarByProviderKeyAsync(string providerKey, int version = 0)
        {
            // providerKey = EVM address on ZKsync Era
            var result = new OASISResult<IAvatar>();
            try
            {
                var balanceHex = await RpcAsync("eth_getBalance", new object[] { providerKey, "latest" });
                var txCountHex = await RpcAsync("eth_getTransactionCount", new object[] { providerKey, "latest" });

                var avatar = new Avatar();
                avatar.ProviderUniqueStorageKey[Core.Enums.ProviderType.ZkSyncSSOOASIS] = providerKey;
                avatar.Username = providerKey;

                var balStr = balanceHex.GetString() ?? "0x0";
                avatar.MetaData["zksync_balance_hex"] = balStr;
                if (txCountHex.ValueKind == JsonValueKind.String)
                {
                    var txCountStr = txCountHex.GetString() ?? "0x0";
                    if (txCountStr.StartsWith("0x") && int.TryParse(txCountStr[2..], System.Globalization.NumberStyles.HexNumber, null, out var txCount))
                        avatar.MetaData["zksync_tx_count"] = txCount.ToString();
                }
                result.Result = avatar;
            }
            catch (Exception ex) { result.Exception = ex; OASISErrorHandling.HandleError(ref result, ex.Message); }
            return result;
        }
