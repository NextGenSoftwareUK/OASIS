        private bool _isActivated;

        public ZkSyncSSOOASIS(string rpcUrl = "https://mainnet.era.zksync.io/")
        {
            _rpcUrl = rpcUrl;
            _rpcHttp = new HttpClient();
            _rpcHttp.DefaultRequestHeaders.Add("Accept", "application/json");
            _explorerHttp = new HttpClient { BaseAddress = new Uri("https://block-explorer-api.mainnet.zksync.io") };
            _explorerHttp.DefaultRequestHeaders.Add("Accept", "application/json");

            ProviderName = "ZkSyncSSOOASIS";
            ProviderDescription = "ZKsync SSO provider — passkey smart accounts on ZKsync Era";
            ProviderType = new EnumValue<ProviderType>(Core.Enums.ProviderType.ZkSyncSSOOASIS);
            ProviderCategory = new EnumValue<ProviderCategory>(Core.Enums.ProviderCategory.StorageAndNetwork);
            ProviderCategories.Add(new EnumValue<ProviderCategory>(Core.Enums.ProviderCategory.Network));
        }

        private async Task<JsonElement> RpcAsync(string method, object[] rpcParams)
        {
            var payload = new { jsonrpc = "2.0", id = 1, method, @params = rpcParams };
            var response = await _rpcHttp.PostAsJsonAsync(_rpcUrl, payload);
            response.EnsureSuccessStatusCode();
            var body = await response.Content.ReadFromJsonAsync<JsonElement>();
            if (body.TryGetProperty("error", out var err)) throw new Exception(err.GetRawText());
            return body.TryGetProperty("result", out var r) ? r : body;
        }

        public override async Task<OASISResult<bool>> ActivateProviderAsync()
        {
            var result = new OASISResult<bool>();
            try
            {
                await RpcAsync("eth_chainId", Array.Empty<object>());
                _isActivated = true; result.Result = true; result.Message = "ZkSyncSSOOASIS activated.";
            }
            catch (Exception ex) { result.Exception = ex; OASISErrorHandling.HandleError(ref result, ex.Message); }
            return result;
        }
        public override OASISResult<bool> ActivateProvider() => ActivateProviderAsync().Result;
        public override async Task<OASISResult<bool>> DeActivateProviderAsync() { _isActivated = false; return await Task.FromResult(new OASISResult<bool>(true)); }
        public override OASISResult<bool> DeActivateProvider() => DeActivateProviderAsync().Result;

